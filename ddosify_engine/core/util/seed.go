package util

func splitmix64(x uint64) uint64 {
	x += 0x9e3779b97f4a7c15
	x = (x ^ (x >> 30)) * 0xbf58476d1ce4e5b9
	x = (x ^ (x >> 27)) * 0x94d049bb133111eb
	return x ^ (x >> 31)
}

// SeedMix derives a well spread value from a seed and two counters, the same on every run.
// Stateless, so concurrent iterations need no lock and their draws do not depend on goroutine order.
func SeedMix(seed int64, a, b uint64) uint64 {
	return splitmix64(splitmix64(splitmix64(uint64(seed))^a) ^ b)
}

// StringHash is FNV-1a of s, without allocating.
func StringHash(s string) uint64 {
	h := uint64(14695981039346656037)
	for i := 0; i < len(s); i++ {
		h ^= uint64(s[i])
		h *= 1099511628211
	}
	return h
}
